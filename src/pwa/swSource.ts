/*
 * The service worker that lets the installed game run offline, written out at
 * build time (vite.config.ts) with the list of files the build made.
 *
 *  - the game's own files are cached when it's installed and served from the
 *    cache from then on (each build has its own cache, so an update swaps
 *    the whole set at once and the old one is deleted);
 *  - the page itself is fetched fresh when there's a connection (so updates
 *    arrive on the next launch) and comes from the cache when there isn't;
 *  - fonts and the hand-tracking library are kept after their first load,
 *    so they work offline too. Everything else (lyrics lookups) goes straight
 *    to the network.
 */

/** cross-origin hosts whose files are kept for offline use (fonts, Air DJ's hand tracker) */
export const RUNTIME_HOSTS = ['fonts.googleapis.com', 'fonts.gstatic.com', 'cdn.jsdelivr.net', 'storage.googleapis.com'];

/** the files under the build folder the worker caches up front (paths relative to it) */
export function precacheList(files: string[]): string[] {
  const skip = new Set(['sw.js', '_headers', '_redirects']);
  const list = files.map((f) => f.replace(/\\/g, '/')).filter((f) => !skip.has(f) && !f.endsWith('.map') && !f.startsWith('.'));
  // the page is fetched by its folder ('./'), which is how a launch asks for it
  return ['./', ...list.filter((f) => f !== 'index.html')].sort((a, b) => (a === './' ? -1 : b === './' ? 1 : a.localeCompare(b)));
}

export function serviceWorkerSource(files: string[], version: string): string {
  const precache = precacheList(files);
  return `/* Deckhouse DJ offline cache, build ${version}. Generated by vite.config.ts; don't edit. */
const VERSION = ${JSON.stringify(version)};
const CACHE = 'deckhouse-' + VERSION;
const RUNTIME = 'deckhouse-runtime';
const PRECACHE = ${JSON.stringify(precache)};
const RUNTIME_HOSTS = ${JSON.stringify(RUNTIME_HOSTS)};
const PAGE = new URL('./', self.registration.scope).href;

self.addEventListener('install', (e) => {
  e.waitUntil(
    caches.open(CACHE).then((c) => c.addAll(PRECACHE.map((p) => new Request(new URL(p, self.registration.scope).href, { cache: 'reload' })))).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('deckhouse-') && k !== CACHE && k !== RUNTIME).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

/* the page: fresh when online (give up after a few seconds), the cached copy when not */
async function page(req) {
  const cache = await caches.open(CACHE);
  try {
    const ctl = new AbortController();
    const timer = setTimeout(() => ctl.abort(), 4000);
    const res = await fetch(req, { signal: ctl.signal });
    clearTimeout(timer);
    if (res.ok) {
      cache.put(PAGE, res.clone());
      return res;
    }
  } catch {}
  return (await cache.match(PAGE)) || (await cache.match(req, { ignoreSearch: true })) || Response.error();
}

async function own(req) {
  const hit = await caches.match(req, { ignoreSearch: true });
  if (hit) return hit;
  const res = await fetch(req);
  if (res.ok && res.type === 'basic') (await caches.open(CACHE)).put(req, res.clone());
  return res;
}

/* kept after the first load; refreshed in the background */
async function runtime(req, e) {
  const cache = await caches.open(RUNTIME);
  const hit = await cache.match(req);
  const fresh = fetch(req)
    .then((res) => {
      if (res.ok || res.type === 'opaque') return cache.put(req, res.clone()).then(() => res);
      return res;
    })
    .catch(() => hit || Response.error());
  if (hit) {
    e.waitUntil(fresh.catch(() => {}));
    return hit;
  }
  return fresh;
}

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || req.headers.has('range')) return;
  const url = new URL(req.url);
  if (req.mode === 'navigate' && url.origin === self.location.origin) e.respondWith(page(req));
  else if (url.origin === self.location.origin) e.respondWith(own(req));
  else if (RUNTIME_HOSTS.includes(url.hostname)) e.respondWith(runtime(req, e));
});
`;
}
